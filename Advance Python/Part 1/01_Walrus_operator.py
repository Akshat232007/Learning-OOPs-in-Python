item = [1,2,44,42,4,2332]

if ((n := len(item)) > 3):
    print("List Overflow!!")
    
    
# Walrus Operator (:=), also known as the Assignment Expression Operator.

# It is used to assign a value to a variable and use that
# variable within the same expression.

# Example:
# Without Walrus Operator, the same code would look like:

# item = [1, 2, 44, 42, 4, 2332]
#
# n = len(item)
#
# if n > 3:
#     print("List Overflow!!")

# = : assigns a value to a variable
# := : assigns a value to a variable and returns that assigned value as an expression